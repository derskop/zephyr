/*
 * N32G45x pinmux bit fields (remap encoded in pinmux):
 *   mode[0:1]     ALTERNATE / GPIO_IN / ANALOG / GPIO_OUT
 *   line[2:5]     pin number 0-15
 *   port[6:9]     port number, 'A'-based
 *   rm[10:19]     remap opcode (see N32G45X_REMAP), 0 = no remap
 */
#define N32G45X_MODE_SHIFT   0U
#define N32G45X_MODE_MASK    0x3U
#define N32G45X_LINE_SHIFT   2U
#define N32G45X_LINE_MASK    0xFU
#define N32G45X_PORT_SHIFT   6U
#define N32G45X_PORT_MASK    0xFU
#define N32G45X_RM_SHIFT     10U
#define N32G45X_RM_MASK      0x3FFU

/* Mode enums */
#define ALTERNATE  0x0 /* Alternate function output */
#define GPIO_IN    0x1 /* Input */
#define ANALOG     0x2 /* Analog input */
#define GPIO_OUT   0x3 /* General purpose output */

/*
 * Remap opcode bit fields (10 bits, stored in pinmux[10:19]):
 *   val[0:1]     remap value (0-3)
 *   w[2]         remap field width: 0 = 1 bit, 1 = 2 bits
 *   reg[3:4]     remap register:
 *                0 = AFIO_RMP_CFG, 1 = AFIO_RMP_CFG3, 2 = AFIO_RMP_CFG4
 *                3 = remap bits split across two registers
 *   bit[5:9]     bit position of the remap field in the register
 */
#define N32G45X_RM_VAL_SHIFT 0U
#define N32G45X_RM_VAL_MASK  0x3U
#define N32G45X_RM_W_SHIFT   2U
#define N32G45X_RM_W_MASK    0x1U
#define N32G45X_RM_REG_SHIFT 3U
#define N32G45X_RM_REG_MASK  0x3U
#define N32G45X_RM_BIT_SHIFT 5U
#define N32G45X_RM_BIT_MASK  0x1FU

/* Decode accessors for the remap opcode */
#define N32G45X_RM_VAL_GET(rmap) \
	(((rmap) >> N32G45X_RM_VAL_SHIFT) & N32G45X_RM_VAL_MASK)
#define N32G45X_RM_W_GET(rmap) \
	(((rmap) >> N32G45X_RM_W_SHIFT) & N32G45X_RM_W_MASK)
#define N32G45X_RM_REG_GET(rmap) \
	(((rmap) >> N32G45X_RM_REG_SHIFT) & N32G45X_RM_REG_MASK)
#define N32G45X_RM_BIT_GET(rmap) \
	(((rmap) >> N32G45X_RM_BIT_SHIFT) & N32G45X_RM_BIT_MASK)

/* Remap register selectors */
#define N32G45X_RMP_CFG   0U
#define N32G45X_RMP_CFG3  1U
#define N32G45X_RMP_CFG4  2U
/* Split remap: SPI1 (RMP_CFG.0 + RMP_CFG3.18) and USART2 (RMP_CFG.3 +
 * RMP_CFG3.19) have their remap bits spread over two registers. The bit
 * field carries the position of the low bit (0 for SPI1, 3 for USART2). */
#define N32G45X_RMP_SPLIT 3U

/**
 * Encode a remap opcode: value, field width (0 = 1 bit, 1 = 2 bits),
 * register selector and bit position.
 */
#define N32G45X_REMAP(val, w, reg, bit)                                    \
	((((val) & N32G45X_RM_VAL_MASK) << N32G45X_RM_VAL_SHIFT) |          \
	 (((w) & N32G45X_RM_W_MASK) << N32G45X_RM_W_SHIFT) |                \
	 (((reg) & N32G45X_RM_REG_MASK) << N32G45X_RM_REG_SHIFT) |          \
	 (((bit) & N32G45X_RM_BIT_MASK) << N32G45X_RM_BIT_SHIFT))

/** Encode a pinmux value: port ('A'-based), line, mode and remap opcode. */
#define N32G45X_PINMUX(port, line, mode, remap)                            \
	(((((port) - 'A') & N32G45X_PORT_MASK) << N32G45X_PORT_SHIFT) |     \
	 (((line) & N32G45X_LINE_MASK) << N32G45X_LINE_SHIFT) |             \
	 (((mode) & N32G45X_MODE_MASK) << N32G45X_MODE_SHIFT) |             \
	 (((remap) & N32G45X_RM_MASK) << N32G45X_RM_SHIFT))

/** No remap sentinel: the device cannot be remapped. */
#define NO_REMAP 0

