#define N32_RESET_TSC    N32_RESET_CONFIG(APB1PRST, 10U)
#define N32_RESET_WWDG   N32_RESET_CONFIG(APB1PRST, 11U)
#define N32_RESET_SPI2   N32_RESET_CONFIG(APB1PRST, 14U)
#define N32_RESET_SPI3   N32_RESET_CONFIG(APB1PRST, 15U)
